//! Reproducible Quantize assets from two readable SVG masters, without platform tools.

use std::{collections::BTreeMap, fmt::Write as _, fs, path::Path};

use resvg::{
    tiny_skia::{Pixmap, PixmapPaint, Transform},
    usvg,
};

use crate::{Error, Result, workspace::Workspace};

const MASTER: &str = "packaging/macos/icon.svg";
const SMALL: &str = "packaging/macos/mark-small.svg";
const ICONSET: &str = "packaging/macos/Voxelite.iconset";
const PREVIEW: &str = "docs/images/quantize-preview.png";
const SIZES: &[u32] = &[16, 32, 64, 128, 256, 512, 1024];

struct Artwork {
    icon: String,
    small_icon: String,
    mark: String,
    small_mark: String,
}

impl Artwork {
    fn load(workspace: &Workspace) -> Result<Self> {
        let icon = workspace.read(MASTER)?;
        let small_mark = workspace.read(SMALL)?;
        let doc = roxmltree::Document::parse(&icon).map_err(invalid)?;
        let mark = doc
            .descendants()
            .find(|n| n.attribute("id") == Some("mark"))
            .ok_or_else(|| invalid("icon.svg needs a self-contained group with id=mark"))?;
        let range = mark.range();
        let mark = format!(
            "<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"224 224 576 576\">\n  <title>Quantum — Quantize mark</title>\n  <!-- Generated by cargo xtask icons from packaging/macos/icon.svg. -->\n{}\n</svg>\n",
            &icon[range.clone()]
        );
        let small = roxmltree::Document::parse(&small_mark).map_err(invalid)?;
        let body: String = small
            .root_element()
            .children()
            .filter(|n| n.is_element() && !n.has_tag_name("title"))
            .map(|n| &small_mark[n.range()])
            .collect();
        let mut small_icon = icon.clone();
        small_icon.replace_range(range, &format!("<g>{body}</g>"));
        Ok(Self {
            icon,
            small_icon,
            mark,
            small_mark,
        })
    }

    fn icon(&self, logical_size: u32) -> &str {
        if logical_size <= 32 {
            &self.small_icon
        } else {
            &self.icon
        }
    }
}

/// Regenerate all tracked derivatives, or check them without modifying files.
///
/// The optical master is selected by logical size, including Retina representations.
/// The optional preview copy is useful outside the repository for design review.
#[expect(
    clippy::print_stdout,
    reason = "CLI output: reports the generated or checked asset count"
)]
pub fn generate(workspace: &Workspace, check: bool, preview: Option<&Path>) -> Result<()> {
    let art = Artwork::load(workspace)?;
    let mut assets = BTreeMap::new();
    for &size in SIZES {
        for scale in [1, 2] {
            if size * scale > 1024 {
                continue;
            }
            let suffix = if scale == 2 { "@2x" } else { "" };
            assets.insert(
                format!("{ICONSET}/icon_{size}x{size}{suffix}.png"),
                png(&render(art.icon(size), size * scale)?)?,
            );
        }
    }
    assets.insert(
        "packaging/macos/icon-1024.png".into(),
        assets[&format!("{ICONSET}/icon_512x512@2x.png")].clone(),
    );
    assets.insert(
        "crates/voxelite-app/assets/app-icon-256.png".into(),
        assets[&format!("{ICONSET}/icon_256x256.png")].clone(),
    );
    assets.insert("packaging/macos/Voxelite.icns".into(), icns(&assets)?);
    assets.insert("site/assets/mark.svg".into(), art.mark.as_bytes().to_vec());
    assets.insert(
        "site/assets/favicon.svg".into(),
        art.small_mark.as_bytes().to_vec(),
    );
    for size in [16, 32] {
        assets.insert(
            format!("site/assets/favicon-{size}.png"),
            png(&render(&art.small_mark, size)?)?,
        );
    }
    assets.insert(PREVIEW.into(), preview_image(workspace, &art)?);
    if let Some(path) = preview {
        write(path, &assets[PREVIEW])?;
    }
    let mut stale = Vec::new();
    for (path, bytes) in &assets {
        let path = workspace.path(path);
        if check {
            if fs::read(&path).ok().as_ref() != Some(bytes) {
                stale.push(path.display().to_string());
            }
        } else {
            write(&path, bytes)?;
        }
    }
    if !stale.is_empty() {
        return Err(invalid(format!(
            "stale icon assets; run cargo xtask icons:\n{}",
            stale.join("\n")
        )));
    }
    println!(
        "{} {} Quantize assets",
        if check { "checked" } else { "generated" },
        assets.len()
    );
    Ok(())
}

fn invalid(error: impl std::fmt::Display) -> Error {
    Error::Invalid(format!("icons: {error}"))
}

fn write(path: &Path, bytes: &[u8]) -> Result<()> {
    if let Some(parent) = path.parent().filter(|p| !p.as_os_str().is_empty()) {
        fs::create_dir_all(parent).map_err(|source| Error::Io {
            path: parent.into(),
            source,
        })?;
    }
    fs::write(path, bytes).map_err(|source| Error::Io {
        path: path.into(),
        source,
    })
}

fn render(svg: &str, size: u32) -> Result<Pixmap> {
    let tree = usvg::Tree::from_str(svg, &usvg::Options::default()).map_err(invalid)?;
    let mut image = Pixmap::new(size, size).ok_or_else(|| invalid("invalid image dimensions"))?;
    resvg::render(
        &tree,
        Transform::from_scale(
            size as f32 / tree.size().width(),
            size as f32 / tree.size().height(),
        ),
        &mut image.as_mut(),
    );
    Ok(image)
}

fn png(image: &Pixmap) -> Result<Vec<u8>> {
    image.encode_png().map_err(invalid)
}

/// PNG-backed ICNS elements for macOS 13+, with explicit logical-size/scale mapping.
/// No resizing or re-encoding happens while assembling the container.
fn icns(assets: &BTreeMap<String, Vec<u8>>) -> Result<Vec<u8>> {
    let mut bytes = b"icns\0\0\0\0".to_vec();
    for (kind, name) in [
        (b"icp4", "icon_16x16.png"),
        (b"ic11", "icon_16x16@2x.png"),
        (b"icp5", "icon_32x32.png"),
        (b"ic12", "icon_32x32@2x.png"),
        (b"ic07", "icon_128x128.png"),
        (b"ic13", "icon_128x128@2x.png"),
        (b"ic08", "icon_256x256.png"),
        (b"ic14", "icon_256x256@2x.png"),
        (b"ic09", "icon_512x512.png"),
        (b"ic10", "icon_512x512@2x.png"),
    ] {
        let data = &assets[&format!("{ICONSET}/{name}")];
        let length = u32::try_from(data.len() + 8).map_err(invalid)?;
        bytes.extend(kind);
        bytes.extend(length.to_be_bytes());
        bytes.extend(data);
    }
    let length = u32::try_from(bytes.len()).map_err(invalid)?;
    bytes[4..8].copy_from_slice(&length.to_be_bytes());
    Ok(bytes)
}

fn preview_image(workspace: &Workspace, art: &Artwork) -> Result<Vec<u8>> {
    let mut svg = String::from(
        r##"<svg xmlns="http://www.w3.org/2000/svg" width="2304" height="1536">
<rect width="2304" height="1536" fill="#171717"/>
<rect x="1088" y="768" width="1216" height="768" fill="#f5f5f5"/>
<rect x="544" y="1168" width="480" height="320" fill="#f5f5f5"/>
<g font-family="Geist" font-size="24" fill="#b5b5b5">
<text x="64" y="64">QUANTUM / QUANTIZE</text>
<text x="64" y="104">1024 px · approved grid · hard seam</text>
<text x="1120" y="64">DARK / ACTUAL PIXEL SIZES</text>
<text x="1120" y="832" fill="#555">LIGHT / ACTUAL PIXEL SIZES</text>
<text x="64" y="1216">MARK / 192 px</text>
<text x="576" y="1216" fill="#555">MARK / 192 px</text>
"##,
    );
    for (y, fill) in [(0, "#b5b5b5"), (768, "#555")] {
        for (size, x) in [(512, 1120), (128, 1680), (64, 1864), (32, 1992), (16, 2112)] {
            let _ = write!(
                svg,
                r#"<text x="{x}" y="{}" fill="{fill}">{size}</text>"#,
                y + 656
            );
        }
        let _ = write!(
            svg,
            r#"<text x="1120" y="{}" fill="{fill}">16 / 32 px use the four-row optical master.</text>"#,
            y + 712
        );
    }
    svg.push_str("</g></svg>");
    let mut options = usvg::Options::default();
    let font = workspace.path("crates/voxelite-app/assets/fonts/Geist.ttf");
    options
        .fontdb_mut()
        .load_font_data(fs::read(&font).map_err(|source| Error::Io { path: font, source })?);
    let tree = usvg::Tree::from_str(&svg, &options).map_err(invalid)?;
    let mut image = Pixmap::new(2304, 1536).ok_or_else(|| invalid("preview allocation failed"))?;
    resvg::render(&tree, Transform::identity(), &mut image.as_mut());
    let mut place = |source: &str, size, x, y| -> Result<()> {
        image.draw_pixmap(
            x,
            y,
            render(source, size)?.as_ref(),
            &PixmapPaint::default(),
            Transform::identity(),
            None,
        );
        Ok(())
    };
    place(&art.icon, 1024, 0, 112)?;
    for row in [0, 768] {
        for (size, x) in [(512, 1120), (128, 1680), (64, 1864), (32, 1992), (16, 2112)] {
            place(art.icon(size), size, x, row + 112 + (512 - size as i32) / 2)?;
        }
    }
    place(&art.mark, 192, 160, 1256)?;
    place(&art.mark, 192, 672, 1256)?;
    png(&image)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn mark_has_transparent_tile_and_hard_seam() {
        let art = Artwork::load(&Workspace::discover().unwrap()).unwrap();
        // Use the master coordinates so seam samples are exact pixel columns.
        let mark = art.mark.replace("224 224 576 576", "0 0 1024 1024");
        let image = render(&mark, 1024).unwrap();
        assert_eq!(image.pixel(100, 100).unwrap().alpha(), 0);
        assert_eq!(image.pixel(508, 500).unwrap().alpha(), 255);
        for x in 509..514 {
            assert_eq!(image.pixel(x, 500).unwrap().alpha(), 0);
        }
        assert_eq!(image.pixel(520, 490).unwrap().alpha(), 255);
        let small = render(
            &art.small_mark.replace("224 224 576 576", "0 0 1024 1024"),
            1024,
        )
        .unwrap();
        assert_eq!(small.pixel(508, 500).unwrap().alpha(), 255);
        for x in 509..520 {
            assert_eq!(small.pixel(x, 500).unwrap().alpha(), 0);
        }
    }

    #[test]
    fn generated_assets_are_current_and_icns_frames_decode() {
        let workspace = Workspace::discover().unwrap();
        generate(&workspace, true, None).unwrap();
        let bytes = fs::read(workspace.path("packaging/macos/Voxelite.icns")).unwrap();
        assert_eq!(&bytes[..4], b"icns");
        let number = |b: &[u8]| u32::from_be_bytes(b.try_into().unwrap()) as usize;
        assert_eq!(number(&bytes[4..8]), bytes.len());
        let mut at = 8;
        let mut sizes = Vec::new();
        while at < bytes.len() {
            let length = number(&bytes[at + 4..at + 8]);
            let image = Pixmap::decode_png(&bytes[at + 8..at + length]).unwrap();
            assert_eq!(image.width(), image.height());
            sizes.push(image.width());
            at += length;
        }
        assert_eq!(at, bytes.len());
        assert_eq!(sizes, [16, 32, 32, 64, 128, 256, 256, 512, 512, 1024]);
        // Retina 32 pt uses the small grid; a 64 pt image uses the approved full grid.
        assert_ne!(
            fs::read(workspace.path(format!("{ICONSET}/icon_32x32@2x.png"))).unwrap(),
            fs::read(workspace.path(format!("{ICONSET}/icon_64x64.png"))).unwrap()
        );
    }
}
